(function () {
  const trigger = document.querySelector('.lang-trigger');
  const menu = document.querySelector('.lang-menu');
  const options = document.querySelectorAll('.lang-dropdown [data-lang]');
  const translatable = document.querySelectorAll('[data-i18n]');

  function setLanguage(language) {
    const dictionary = appPageTranslations[language] || appPageTranslations.en;
    translatable.forEach((node) => {
      const key = node.dataset.i18n;
      if (dictionary[key]) {
        node.textContent = dictionary[key];
      }
    });
    options.forEach((option) => {
      option.classList.toggle('active', option.dataset.lang === language);
    });
    if (trigger) {
      trigger.textContent = language.toUpperCase();
    }
    document.documentElement.lang = language;
    if (menu) {
      menu.classList.remove('open');
    }
  }

  if (trigger && menu) {
    trigger.addEventListener('click', () => {
      menu.classList.toggle('open');
    });

    document.addEventListener('click', (event) => {
      if (!menu.contains(event.target)) {
        menu.classList.remove('open');
      }
    });
  }

  options.forEach((option) => {
    option.addEventListener('click', () => setLanguage(option.dataset.lang));
  });

  setLanguage('en');
})();

(function () {
  const carousels = Array.from(document.querySelectorAll('.deskx-carousel'));
  if (!carousels.length) return;

  carousels.forEach((carousel) => {
    const slides = Array.from(carousel.querySelectorAll('.deskx-slide'));
    const dots = Array.from(carousel.querySelectorAll('.deskx-dots button'));
    if (!slides.length || !dots.length) return;

    let activeIndex = 0;
    let timer = null;

    function showSlide(index) {
      activeIndex = (index + slides.length) % slides.length;
      slides.forEach((slide, slideIndex) => {
        slide.classList.toggle('active', slideIndex === activeIndex);
      });
      dots.forEach((dot, dotIndex) => {
        dot.classList.toggle('active', dotIndex === activeIndex);
      });
    }

    function startAutoPlay() {
      stopAutoPlay();
      timer = window.setInterval(() => {
        showSlide(activeIndex + 1);
      }, 4200);
    }

    function stopAutoPlay() {
      if (timer) {
        window.clearInterval(timer);
        timer = null;
      }
    }

    dots.forEach((dot) => {
      dot.addEventListener('click', () => {
        showSlide(Number(dot.dataset.slide));
        startAutoPlay();
      });
    });

    carousel.addEventListener('mouseenter', stopAutoPlay);
    carousel.addEventListener('mouseleave', startAutoPlay);
    startAutoPlay();
  });
})();

(function () {
  const shots = Array.from(document.querySelectorAll('.parallax-shot'));
  if (!shots.length) return;

  let ticking = false;

  function updateParallaxShots() {
    const viewportHeight = window.innerHeight || 1;
    shots.forEach((shot, index) => {
      const rect = shot.getBoundingClientRect();
      const center = rect.top + rect.height / 2;
      const progress = (center - viewportHeight / 2) / viewportHeight;
      const strength = index % 2 === 0 ? -44 : 44;
      shot.style.setProperty('--parallax-y', `${progress * strength}px`);
    });
    ticking = false;
  }

  function requestUpdate() {
    if (!ticking) {
      window.requestAnimationFrame(updateParallaxShots);
      ticking = true;
    }
  }

  window.addEventListener('scroll', requestUpdate, { passive: true });
  window.addEventListener('resize', requestUpdate);
  updateParallaxShots();
})();

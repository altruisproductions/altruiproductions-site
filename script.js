const texts = document.querySelectorAll('[data-key]');
const langMenu = document.querySelector('.lang-menu');
const langTrigger = document.querySelector('.lang-trigger');
const langOptions = document.querySelectorAll('.lang-option');

function setLanguage(language) {
  const dictionary = translations[language] || translations.en;
  texts.forEach((node) => {
    const key = node.dataset.key;
    if (dictionary[key]) {
      node.textContent = dictionary[key];
    }
  });

  langOptions.forEach((button) => {
    button.classList.toggle('active', button.dataset.lang === language);
  });

  // Aggiorna il testo del trigger (solo il testo, l'arrow è in CSS)
  const shortLangCode = language.toUpperCase();
  langTrigger.textContent = shortLangCode;

  document.documentElement.lang = language;
  
  // Chiudi dropdown dopo aver selezionato
  langMenu.classList.remove('open');
}

// Toggle dropdown
langTrigger.addEventListener('click', () => {
  langMenu.classList.toggle('open');
});

// Click su opzioni
langOptions.forEach((option) => {
  option.addEventListener('click', () => {
    setLanguage(option.dataset.lang);
  });
});

// Chiudi dropdown se clicchi fuori
document.addEventListener('click', (e) => {
  if (!langMenu.contains(e.target)) {
    langMenu.classList.remove('open');
  }
});


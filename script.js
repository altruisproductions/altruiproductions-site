const trailerButtons = document.querySelectorAll('#openTrailer, #openTrailerSecondary');
const trailerModal = document.getElementById('trailerModal');
const trailerPlayer = document.getElementById('trailerPlayer');
const closeTrailer = document.getElementById('closeTrailer');
const closeBackdrop = document.getElementById('closeTrailerBackdrop');
const trailerUrl = 'https://video.fastly.steamstatic.com/store_trailers/4259720/1126138106/5d3fd9376ee6e64f124b0850a736b839afb891eb/1765983718/hls_264_master.m3u8?t=1766183205';
let trailerHls = null;
let trailerCloseTimer = null;

function openTrailerModal() {
  if (trailerCloseTimer) {
    window.clearTimeout(trailerCloseTimer);
    trailerCloseTimer = null;
  }
  if (trailerPlayer.canPlayType('application/vnd.apple.mpegurl')) {
    trailerPlayer.src = trailerUrl;
    trailerPlayer.load();
  } else if (window.Hls && window.Hls.isSupported()) {
    trailerHls = new window.Hls({
      startLevel: 0,
      capLevelToPlayerSize: false
    });
    trailerHls.loadSource(trailerUrl);
    trailerHls.attachMedia(trailerPlayer);
  }
  trailerModal.classList.add('open');
  trailerModal.setAttribute('aria-hidden', 'false');
  document.body.classList.add('no-scroll');
  trailerPlayer.play().catch(() => {
    // Some browsers require the user to press play even after opening the modal.
  });
}

function closeTrailerModal() {
  trailerModal.classList.remove('open');
  trailerModal.setAttribute('aria-hidden', 'true');
  trailerCloseTimer = window.setTimeout(() => {
    trailerPlayer.pause();
    if (trailerHls) {
      trailerHls.destroy();
      trailerHls = null;
    }
    trailerPlayer.removeAttribute('src');
    trailerPlayer.load();
    document.body.classList.remove('no-scroll');
    trailerCloseTimer = null;
  }, 420);
}

trailerButtons.forEach((button) => {
  button.addEventListener('click', openTrailerModal);
});

closeTrailer.addEventListener('click', closeTrailerModal);
closeBackdrop.addEventListener('click', closeTrailerModal);

window.addEventListener('keydown', (event) => {
  if (event.key === 'Escape' && trailerModal.classList.contains('open')) {
    closeTrailerModal();
  }
});

// ── Parallax professionale con zoom dinamico e easing ──────────────────────
(function () {
  const panels = Array.from(document.querySelectorAll('.parallax-panel'));
  let ticking = false;
  
  // Cubic easing function per transizioni fluide
  const easeOutCubic = (t) => 1 - Math.pow(1 - t, 3);
  const easeInOutQuad = (t) => t < 0.5 ? 2 * t * t : -1 + (4 - 2 * t) * t;

  function updateParallax() {
    const vh = window.innerHeight;

    panels.forEach((panel) => {
      const speed = parseFloat(panel.dataset.speed) || 0.42;
      const layer = panel.querySelector('.parallax-layer');
      const copy  = panel.querySelector('.parallax-copy');
      if (!layer) return;

      const rect     = panel.getBoundingClientRect();
      const visible  = rect.bottom > 0 && rect.top < vh;
      if (!visible) return;

      // progress: 0 = panel appena entrato dal basso, 1 = panel uscito in alto
      const rawProgress = (vh - rect.top) / (vh + rect.height);
      const progress = Math.min(Math.max(rawProgress, 0), 1);
      
      // Easing per movimento più naturale
      const easedProgress = easeInOutQuad(progress);

      // ── Movimento parallasse ──
      // Si muove più lentamente del contenuto per creare depth
      const imgOffset = (easedProgress - 0.5) * rect.height * speed;
      
      // ── Zoom dinamico e professionale ──
      // Parte da 1.0 e sale progressivamente a 1.25 durante lo scroll
      // La curva è ease-out per un effetto più naturale
      const zoomMinScale = 1.0;
      const zoomMaxScale = 1.25;
      const zoomProgression = easeOutCubic(progress);
      const scale = zoomMinScale + (zoomMaxScale - zoomMinScale) * zoomProgression;

      // Applica sia parallasse che zoom con 3D acceleration
      layer.style.transform = `translate3d(0, ${imgOffset}px, 0) scale(${scale})`;

      // ── Effetto fade-in del testo ──
      // Il testo entra più velocemente dell'immagine per drammaticità
      if (copy) {
        // Trigger fade-in quando panel è al 40% della viewport
        const enterStart = 0.2;
        const enterEnd = 0.65;
        const enterRange = enterEnd - enterStart;
        const enterProgress = Math.min(Math.max((progress - enterStart) / enterRange, 0), 1);
        
        // Easing cubic per entrata fluida
        const easedEnter = easeOutCubic(enterProgress);
        const opacity = easedEnter;
        const textY = (1 - easedEnter) * 40;
        
        copy.style.opacity   = opacity;
        copy.style.transform = `translateY(${textY}px)`;
      }
    });

    ticking = false;
  }

  function onScroll() {
    if (!ticking) {
      requestAnimationFrame(updateParallax);
      ticking = true;
    }
  }

  // Listener passivo per migliore performance
  window.addEventListener('scroll', onScroll, { passive: true });
  
  // Esegui subito per impostare lo stato iniziale senza jitter
  updateParallax();
})();

// ── Gallery Toggle and Carousel ──────────────────────
(function () {
  const galleryToggleBtns = document.querySelectorAll('.gallery-toggle .toggle-btn');
  const galleryPhotos = document.querySelector('.gallery-photos');
  const galleryVideos = document.querySelector('.gallery-videos');
  const carousels = document.querySelectorAll('.gallery .carousel');
  const videoIframe = document.querySelector('.gallery-videos iframe');

  // Toggle between photos and videos
  galleryToggleBtns.forEach(btn => {
    btn.addEventListener('click', () => {
      const type = btn.dataset.type;
      galleryToggleBtns.forEach(b => b.classList.remove('active'));
      btn.classList.add('active');

      if (type === 'photos') {
        galleryPhotos.classList.add('active');
        galleryVideos.classList.remove('active');
        // Stop video when switching to photos
        if (videoIframe) {
          videoIframe.src = videoIframe.src.replace('autoplay=1', 'autoplay=0');
        }
      } else {
        galleryVideos.classList.add('active');
        galleryPhotos.classList.remove('active');
        // Start video when switching to videos
        if (videoIframe) {
          videoIframe.src = videoIframe.src.replace('autoplay=0', 'autoplay=1');
        }
      }
    });
  });

  // Carousel functionality
  carousels.forEach(carousel => {
    const container = carousel.querySelector('.carousel-container');
    const items = container.children;
    const prevBtn = carousel.querySelector('.prev');
    const nextBtn = carousel.querySelector('.next');
    let currentIndex = 0;

    function updateCarousel() {
      const offset = -currentIndex * 100;
      container.style.transform = `translateX(${offset}%)`;
    }

    prevBtn.addEventListener('click', () => {
      currentIndex = currentIndex > 0 ? currentIndex - 1 : items.length - 1;
      updateCarousel();
    });

    nextBtn.addEventListener('click', () => {
      currentIndex = currentIndex < items.length - 1 ? currentIndex + 1 : 0;
      updateCarousel();
    });
  });
})();

